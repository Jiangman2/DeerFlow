// Reproducible web encoding only; symbols and outbound arrows are imagegen pixels.
const fs = require("node:fs/promises");
const path = require("node:path");
const crypto = require("node:crypto");
const sharp = require(
  require.resolve("sharp", {
    paths: [path.dirname(require.resolve("next/package.json"))],
  }),
);
const root = path.resolve(__dirname, "../../..");
const sources = {
  ppt: "exec-b09884cb-e686-4fbb-aa1f-f22a94db78c0.png",
  proofread: "exec-1901fff1-869f-4994-b484-84ba4bfe415c.png",
  translate: "exec-f802bf84-afcc-4103-9434-e92118d9afed.png",
  liveTranscribe: "exec-6f0bce94-ccc1-4696-b374-9ef21de00782.png",
  convert: "exec-266ebadb-76c7-4076-abd6-7a6d52fe34c0.png",
  recordTranscribe: "exec-d2fb7c10-6792-4c54-ae04-df458e3e8d02.png",
  speech: "exec-881549df-2f14-4b84-ada9-c355e1070632.png",
  more: "exec-48ca76dd-7d8c-49c6-a1b2-8d4c67476c34.png",
};
async function bounds(input) {
  const { data, info } = await sharp(input)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] >= 16) {
        left = Math.min(left, x);
        top = Math.min(top, y);
        right = Math.max(right, x);
        bottom = Math.max(bottom, y);
      }
    }
  if (right < left) throw new Error("Empty image");
  return {
    left,
    top,
    width: right - left + 1,
    height: bottom - top + 1,
    canvasWidth: info.width,
    canvasHeight: info.height,
  };
}
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
(async () => {
  const reference = path.join(root, "public/images/action-image.png");
  const ref = await bounds(reference);
  const canvas = 192,
    visible = Math.round(
      (canvas * Math.max(ref.width, ref.height)) /
        Math.max(ref.canvasWidth, ref.canvasHeight),
    );
  const manifest = {
    mode: "built-in image_gen",
    reference: "public/images/action-image.png",
    referenceBounds: ref,
    canvas,
    visibleExtent: visible,
    alphaThreshold: 16,
    arrows: "Baked into generated bitmaps; more has no arrow",
    assets: [],
  };
  const rows = [];
  for (const [id, source] of Object.entries(sources)) {
    const filename = path.join(__dirname, id + ".png");
    // Optional first-run import; later rebuilds use the checked-in PNG sources.
    if (process.argv[2])
      await fs.copyFile(path.join(process.argv[2], source), filename);
    const bytes = await fs.readFile(filename),
      b = await bounds(bytes);
    const factor = visible / Math.max(b.width, b.height);
    const width = Math.round(b.width * factor),
      height = Math.round(b.height * factor);
    const output = await sharp(bytes)
      .extract({ left: b.left, top: b.top, width: b.width, height: b.height })
      .resize(width, height)
      .extend({
        left: Math.floor((canvas - width) / 2),
        right: Math.ceil((canvas - width) / 2),
        top: Math.floor((canvas - height) / 2),
        bottom: Math.ceil((canvas - height) / 2),
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .webp({ quality: 88, alphaQuality: 100, effort: 6 })
      .toBuffer();
    const webName = "portal-3d-20261019-" + id + ".webp";
    await fs.writeFile(path.join(root, "public/images", webName), output);
    rows.push(
      "  " +
        id +
        ': "data:image/webp;base64,' +
        output.toString("base64") +
        '",',
    );
    manifest.assets.push({
      id,
      generatedSource: source,
      pngSha256: sha(bytes),
      originalBounds: b,
      webFile: "public/images/" + webName,
      webBytes: output.length,
      webSha256: sha(output),
      normalizedBounds: await bounds(output),
    });
  }
  await fs.writeFile(
    path.join(root, "src/core/portal-icon-artwork.ts"),
    "// Generated by assets/portal-icons/20261019/build-artwork.cjs.\n// Pre-sized transparent bitmaps: no image optimizer or image HTTP request.\nexport const PORTAL_ICON_ARTWORK = {\n" +
      rows.join("\n") +
      "\n} as const;\n",
  );
  await fs.writeFile(
    path.join(__dirname, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  console.log(
    JSON.stringify(
      {
        canvas,
        visible,
        webBytes: manifest.assets.reduce((n, a) => n + a.webBytes, 0),
        assets: manifest.assets.map(({ id, webBytes, normalizedBounds }) => ({
          id,
          webBytes,
          normalizedBounds,
        })),
      },
      null,
      2,
    ),
  );
})();
